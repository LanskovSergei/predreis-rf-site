import type { ВидТоплива, ВидСообщения, ВходныеДанные, ПутевойЛист, ТипТС, ФормаПЛ } from './types';

/** На шаге 1: легковой → форма 3, грузовой → форма 4-с. */
export function формаПоТипуТС(тип: ТипТС): ФормаПЛ {
  return тип === 'легковой' ? '3' : '4-c';
}

export function названиеФормы(форма: ФормаПЛ): string {
  return форма === '3' ? 'форма № 3' : 'форма № 4-с';
}

export function заголовокПутевогоЛиста(форма: ФормаПЛ, номер: number): string {
  if (форма === '3') {
    return `Путевой лист легкового автомобиля № ${номер} (${названиеФормы('3')})`;
  }
  return `Путевой лист грузового автомобиля № ${номер} (${названиеФормы('4-c')})`;
}

export interface ПолеФормы {
  label: string;
  value: string;
}

export interface КонтекстФормы {
  input: ВходныеДанные;
  лист: ПутевойЛист;
}

function formatFuel(value: ВидТоплива): string {
  return value;
}

function formatMessage(value: ВидСообщения): string {
  const map: Record<ВидСообщения, string> = {
    городское: 'Городское',
    пригородное: 'Пригородное',
    междугородное: 'Междугородное',
    международное: 'Международное',
  };
  return map[value] ?? value;
}

/** Поля для заполнения соответствующей формы ПЛ. */
export function поляФормы(форма: ФормаПЛ, ctx: КонтекстФормы): ПолеФормы[] {
  const { input, лист } = ctx;
  const markModel = `${input.марка} ${input.модель}`.trim();

  const common: ПолеФормы[] = [
    {
      label: форма === '3' ? 'Марка, модель легкового автомобиля' : 'Марка, модель грузового автомобиля',
      value: markModel,
    },
    { label: 'Водитель (Ф.И.О.)', value: лист.водитель },
    { label: 'Время выпуска на линию', value: лист.выпуск },
    { label: 'Время возвращения', value: лист.возвращение },
    { label: 'Показания одометра при выезде, км', value: String(лист.одометрВыдача) },
    { label: 'Показания одометра при возвращении, км', value: String(лист.одометрЗакрытие) },
    { label: 'Пробег, км', value: String(лист.пробег) },
    { label: 'Остаток топлива при выезде, л', value: String(лист.остатокВыдача) },
    { label: 'Остаток топлива при возвращении, л', value: String(лист.остатокЗакрытие) },
    { label: 'Расход топлива по норме, л', value: String(лист.расходНорма) },
    { label: 'Расход топлива фактический, л', value: String(лист.расходФакт) },
    { label: 'Вид топлива', value: formatFuel(input.видТоплива) },
    { label: 'Вид сообщения', value: formatMessage(лист.видСообщения) },
  ];

  if (форма === '3') {
    return common;
  }

  return [
    ...common.slice(0, 1),
    { label: 'Вид перевозки (форма 4-с)', value: 'Сдельная' },
    { label: 'Прицеп или груз', value: input.прицепГруз ? 'Да' : 'Нет' },
    ...common.slice(1),
  ];
}
